package meta

import (
	"errors"
	"fmt"
	"regexp"
	"strings"
)

// The editor format is a small, forgiving subset of Markdown:
//
//	# Attention Is All You Need
//	- Author: Ashish Vaswani, Noam Shazeer
//	- Tags: transformer, attention
//	- Year: 2017
//
//	# Comment
//	Anything you like.
//
//	# Abstract
//	The dominant sequence transduction models ...
//
// Rules:
//   - The first level-1 heading is the title and is mandatory.
//   - `- Key: value` bullets under the title become fields. Author and Tags
//     are known; any other key is stored as an extra field.
//   - `# Comment` and `# Abstract` (any suffix like "(autogenerated)" is
//     ignored) hold free text. Any other level-1 heading is stored as an
//     extra field whose value is the section body, so new fields need no code.
//   - Text before the first heading is ignored.

var (
	headingRE = regexp.MustCompile(`^#\s*(.*)$`)
	bulletRE  = regexp.MustCompile(`^\s*[-*]\s*([^:]+):\s*(.*)$`)
)

// ErrNoTitle is returned when the document has no title heading.
var ErrNoTitle = errors.New("metadata is missing a title (first line: `# Title`)")

// ParseMarkdown converts the editor representation into an Entry.
func ParseMarkdown(src string) (*Entry, error) {
	lines := strings.Split(strings.ReplaceAll(src, "\r\n", "\n"), "\n")
	e := &Entry{Auto: false}

	var (
		section   = "" // current level-1 heading, lowercased
		body      []string
		sawTitle  bool
		bodyStart bool // body of the current section has begun
	)

	flushSection := func() {
		if section == "" || section == "title" {
			body = nil
			return
		}
		text := strings.TrimSpace(strings.Join(body, "\n"))
		switch section {
		case "comment":
			e.Comment = text
		case "abstract":
			e.Abstract = text
		default:
			if text != "" {
				e.SetField(headingKey(section), text)
			}
		}
		body = nil
	}

	for _, raw := range lines {
		line := strings.TrimRight(raw, " \t")
		if m := headingRE.FindStringSubmatch(line); m != nil {
			name := strings.TrimSpace(m[1])
			if !sawTitle {
				if name == "" {
					return nil, ErrNoTitle
				}
				e.Title = strings.TrimSpace(name)
				sawTitle = true
				section = "title"
				bodyStart = false
				continue
			}
			flushSection()
			section = normalizeHeading(name)
			bodyStart = false
			continue
		}

		trimmed := strings.TrimSpace(line)
		if section == "title" {
			if trimmed == "" {
				continue
			}
			if m := bulletRE.FindStringSubmatch(line); m != nil {
				if err := applyField(e, strings.TrimSpace(m[1]), strings.TrimSpace(m[2])); err != nil {
					return nil, err
				}
				continue
			}
			// A stray line right under the title: treat as the start of an
			// anonymous section so it is not silently dropped.
			section = "comment"
			bodyStart = true
			body = append(body, line)
			continue
		}
		if !bodyStart && trimmed == "" {
			continue
		}
		bodyStart = true
		body = append(body, line)
	}
	flushSection()

	e.Title = strings.TrimSpace(e.Title)
	if e.Title == "" {
		return nil, ErrNoTitle
	}
	e.Tags = NormalizeTags(e.Tags)
	if len(e.Tags) == 0 {
		e.Tags = nil
	}
	if len(e.Fields) == 0 {
		e.Fields = nil
	}
	return e, nil
}

// normalizeHeading lowercases a heading and drops a trailing parenthetical,
// so "# Abstract (autogenerated)" and "# abstract" both mean "abstract".
func normalizeHeading(s string) string {
	s = strings.ToLower(strings.TrimSpace(s))
	if i := strings.Index(s, "("); i >= 0 {
		s = strings.TrimSpace(s[:i])
	}
	return s
}

// headingKey turns a free-form heading into a field key: "Venue / Conference"
// becomes "Venue". Words are preserved as the user wrote them.
func headingKey(orig string) string {
	orig = strings.TrimSpace(orig)
	if i := strings.Index(orig, "("); i >= 0 {
		orig = strings.TrimSpace(orig[:i])
	}
	return orig
}

func applyField(e *Entry, key, value string) error {
	switch strings.ToLower(key) {
	case "title":
		if value != "" {
			e.Title = value
		}
	case "author", "authors":
		e.Author = strings.TrimSpace(value)
	case "tags", "tag":
		if value == "" {
			e.Tags = nil
			return nil
		}
		e.Tags = NormalizeTags([]string{value})
	case "abstract":
		e.Abstract = strings.TrimSpace(value)
	case "comment":
		e.Comment = strings.TrimSpace(value)
	case "auto":
		// ignored: `auto` is managed by non
	default:
		if value == "" {
			return nil
		}
		e.SetField(key, strings.TrimSpace(value))
	}
	return nil
}

// fieldOrder is the preferred display order of extra fields.
var fieldOrder = map[string]int{"year": 0, "venue": 1, "doi": 2, "url": 3}

// FormatMarkdown renders an entry in the editor format.
func FormatMarkdown(e *Entry) string {
	var b strings.Builder
	title := e.Title
	if title == "" {
		title = "Untitled"
	}
	fmt.Fprintf(&b, "# %s\n", title)
	fmt.Fprintf(&b, "- Author: %s\n", e.Author)
	fmt.Fprintf(&b, "- Tags: %s\n", strings.Join(e.Tags, ", "))

	extra := make([]string, 0, len(e.Fields))
	for k := range e.Fields {
		if knownKeys[strings.ToLower(k)] {
			continue
		}
		extra = append(extra, k)
	}
	sortKeys(extra)
	for _, k := range extra {
		v := strings.TrimSpace(e.FieldString(k))
		if v == "" || strings.Contains(v, "\n") {
			continue
		}
		fmt.Fprintf(&b, "- %s: %s\n", k, v)
	}

	if c := strings.TrimSpace(e.Comment); c != "" {
		fmt.Fprintf(&b, "\n# Comment\n%s\n", c)
	}
	if a := strings.TrimSpace(e.Abstract); a != "" {
		fmt.Fprintf(&b, "\n# Abstract (autogenerated)\n%s\n", a)
	}
	for _, k := range extra {
		v := strings.TrimSpace(e.FieldString(k))
		if !strings.Contains(v, "\n") {
			continue
		}
		fmt.Fprintf(&b, "\n# %s\n%s\n", k, v)
	}
	return b.String()
}

// sortKeys sorts field keys, keeping the well known ones first.
func sortKeys(keys []string) {
	rank := func(k string) int {
		if r, ok := fieldOrder[strings.ToLower(k)]; ok {
			return r
		}
		return len(fieldOrder)
	}
	for i := 1; i < len(keys); i++ {
		for j := i; j > 0; j-- {
			a, b := keys[j-1], keys[j]
			if rank(a) < rank(b) || (rank(a) == rank(b) && strings.ToLower(a) <= strings.ToLower(b)) {
				break
			}
			keys[j-1], keys[j] = b, a
		}
	}
}

// TemplateMarkdown returns the initial editor content for a file with no
// metadata yet: the extracted entry, with the title prefilled from the
// filename if extraction failed.
func TemplateMarkdown(e *Entry, fallbackTitle string) string {
	c := e.Clone()
	if strings.TrimSpace(c.Title) == "" {
		c.Title = fallbackTitle
	}
	return FormatMarkdown(c)
}
