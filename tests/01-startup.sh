#!/usr/bin/env bash
# Smoke test: the TUI starts, draws its two panes, and exits cleanly.
#
# This is deliberately the simplest possible test. If it is flaky, the whole
# harness is untrustworthy, so it asserts only what cannot be debatable: the
# screen contains the file names, the two pane titles, the status bar, and q
# leaves the terminal in a usable state.

. "$(dirname "$0")/lib.sh"

start alpha.pdf beta.pdf

# The list shows every file.
expect "alpha.pdf"
expect "beta.pdf"
# The panes are titled, and the count is on the list pane.
expect "2 papers"
expect "details"
# The status bar names the mode and offers the keymap.
expect "NORMAL"
expect "q quit"
# Nothing has been extracted yet, so the row is just a name, and the pane
# follows the cursor.
expect_re "alpha\.pdf +││"

# The details pane is showing the selection, not a blank box.
expect "autogenerated"

# Help is reachable and closes again.
send "?"
expect "keys"
send Escape
expect_not "keys"

# q quits. The session ends, which is the assertion: a hang would time out.
send q
for _ in $(seq 1 40); do
	if ! tmux -L "$SOCKET" has-session -t "$SESSION" 2>/dev/null; then
		break
	fi
	sleep 0.05
done
check
if tmux -L "$SOCKET" has-session -t "$SESSION" 2>/dev/null; then
	fail "q did not quit"
else
	pass "q quit the TUI"
fi

finish
